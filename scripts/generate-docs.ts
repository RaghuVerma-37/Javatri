/**
 * Generates the three documents the restaurant owner actually has to act on:
 *
 *   QUESTIONS_FOR_CLIENT.md   things only they can decide
 *   COPY_CHANGES.md           every word we changed, so they can veto any of it
 *   ALLERGEN_TODO.md          the legal blocker, as a worksheet
 *
 * Generated rather than hand-written so they cannot drift from what the seed actually did.
 * Run with `npm run docs`.
 */
